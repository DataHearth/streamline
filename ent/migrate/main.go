//go:build ignore

// Versioned-migration generator. Run via:
//
//	go run -mod=mod ./ent/migrate <name>
//
// Diffs the current ent schema against the replayed migration history and
// writes a new pair of golang-migrate files (<ts>_<name>.up.sql and
// <ts>_<name>.down.sql) into internal/db/migrations/.
//
// The down file is Atlas's reverse of the up, except when the up rebuilds a
// table: SQLite cannot alter most column changes in place (an added column
// that carries an index included), so Atlas copies the table into new_<name>,
// drops the original and renames the copy — and its reverse of that is only
// "DROP TABLE new_<name>", a table that no longer exists on the way down.
// Every down file is therefore checked by running it on the replayed history:
// one that does not restore the previous schema is replaced by Atlas's plan
// from the new schema back to the previous one (a rebuild of its own, which
// copies the rows), and that is checked the same way. Either way both files
// are generated: never hand-edit one.
package main

import (
	"context"
	"database/sql"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/datahearth/streamline/ent/migrate"

	atlasmigrate "ariga.io/atlas/sql/migrate"
	atlasschema "ariga.io/atlas/sql/schema"
	"ariga.io/atlas/sql/sqlite"
	"ariga.io/atlas/sql/sqltool"
	"entgo.io/ent/dialect"
	"entgo.io/ent/dialect/sql/schema"

	// Atlas hard-codes the sqlite3 driver name when opening the dev URL;
	// alias modernc.org/sqlite (already imported by the runtime) under that
	// name so the generator stays CGO-free.
	sqlitedrv "modernc.org/sqlite"
)

const migrationsDir = "internal/db/migrations"

// plannedDownHeader opens a down file checkDown had to replace.
const plannedDownHeader = `-- Generated by ent/migrate: Atlas's own reverse did not restore the
-- previous schema (a table rebuild's reverse drops a new_* table that no
-- longer exists), so this is the plan from the new schema back to it.
`

func init() {
	sql.Register("sqlite3", &sqlitedrv.Driver{})
}

func main() {
	if len(os.Args) != 2 {
		log.Fatalln("usage: go run -mod=mod ./ent/migrate <name>")
	}
	name := os.Args[1]

	if err := os.MkdirAll(migrationsDir, 0o755); err != nil {
		log.Fatalf("create migrations dir: %v", err)
	}
	dir, err := sqltool.NewGolangMigrateDir(migrationsDir)
	if err != nil {
		log.Fatalf("open migrations dir: %v", err)
	}

	opts := []schema.MigrateOption{
		schema.WithDir(dir),
		schema.WithMigrationMode(schema.ModeReplay),
		schema.WithDialect(dialect.SQLite),
		schema.WithFormatter(sqltool.GolangMigrateFormatter),
		schema.WithDropIndex(true),
		schema.WithDropColumn(true),
	}

	before, err := dir.Files()
	if err != nil {
		log.Fatalf("list migrations: %v", err)
	}

	// Throwaway in-memory dev DB for replay; named so multiple pool conns
	// share state.
	ctx := context.Background()
	devURL := "sqlite://atlas-dev?mode=memory&cache=shared&_pragma=foreign_keys(1)"
	if err := migrate.NamedDiff(ctx, devURL, name, opts...); err != nil {
		log.Fatalf("diff: %v", err)
	}

	files, err := dir.Files()
	if err != nil {
		log.Fatalf("list migrations: %v", err)
	}
	if len(files) == len(before) {
		log.Println("schema unchanged, no migration written")
		return
	}
	if err := checkDown(ctx, files); err != nil {
		log.Fatalf("down migration: %v", err)
	}
}

// checkDown proves the newest down file: on the history replayed with the
// newest up applied, the down must bring the schema back to the history
// replayed without it. Atlas's own down fails that for a table rebuild, and
// is then rewritten as the plan from the new schema back to the previous one,
// which must pass the same check.
func checkDown(ctx context.Context, files []atlasmigrate.File) error {
	newest := files[len(files)-1]
	downPath := filepath.Join(
		migrationsDir,
		strings.TrimSuffix(newest.Name(), ".up.sql")+".down.sql",
	)
	oldRealm, err := replayedRealm(ctx, files[:len(files)-1])
	if err != nil {
		return fmt.Errorf("replay previous migrations: %w", err)
	}
	generated, err := os.ReadFile(downPath)
	if err != nil {
		return err
	}
	downErr := downRestores(ctx, files, generated, oldRealm)
	if downErr == nil {
		return nil
	}

	db, drv, err := replay(ctx, files)
	if err != nil {
		return err
	}
	defer db.Close()
	newRealm, err := drv.InspectRealm(ctx, nil)
	if err != nil {
		return err
	}
	changes, err := drv.RealmDiff(newRealm, oldRealm)
	if err != nil {
		return fmt.Errorf("diff schemas: %w", err)
	}
	backward, err := drv.PlanChanges(ctx, "down", changes)
	if err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString(plannedDownHeader)
	for _, c := range backward.Changes {
		if c.Comment != "" {
			fmt.Fprintf(&b, "-- %s\n", c.Comment)
		}
		fmt.Fprintf(&b, "%s;\n", c.Cmd)
	}
	planned := []byte(b.String())
	if err := downRestores(ctx, files, planned, oldRealm); err != nil {
		return fmt.Errorf(
			"planned down step does not restore the schema either: %w",
			err,
		)
	}
	if err := os.WriteFile(downPath, planned, 0o644); err != nil {
		return err
	}
	log.Printf("%s: Atlas's reverse failed (%v), replaced by the planned one",
		downPath, downErr)
	return nil
}

// downRestores applies down to the fully replayed history and reports
// whether the result matches want.
func downRestores(
	ctx context.Context,
	files []atlasmigrate.File,
	down []byte,
	want *atlasschema.Realm,
) error {
	db, drv, err := replay(
		ctx,
		append(slices.Clone(files), atlasmigrate.NewLocalFile("down.sql", down)),
	)
	if err != nil {
		return err
	}
	defer db.Close()
	got, err := drv.InspectRealm(ctx, nil)
	if err != nil {
		return err
	}
	changes, err := drv.RealmDiff(got, want)
	if err != nil {
		return err
	}
	if len(changes) > 0 {
		return fmt.Errorf("%d schema differences remain", len(changes))
	}
	return nil
}

// replayedRealm replays files and inspects the result.
func replayedRealm(
	ctx context.Context,
	files []atlasmigrate.File,
) (*atlasschema.Realm, error) {
	db, drv, err := replay(ctx, files)
	if err != nil {
		return nil, err
	}
	defer db.Close()
	return drv.InspectRealm(ctx, nil)
}

// replay applies the files in order to a fresh in-memory database. One
// connection, so the PRAGMAs a rebuild toggles apply to the statements after
// them.
func replay(
	ctx context.Context,
	files []atlasmigrate.File,
) (*sql.DB, atlasmigrate.Driver, error) {
	db, err := sql.Open("sqlite3", ":memory:?_pragma=foreign_keys(1)")
	if err != nil {
		return nil, nil, err
	}
	db.SetMaxOpenConns(1)
	for _, f := range files {
		stmts, err := f.Stmts()
		if err != nil {
			db.Close()
			return nil, nil, fmt.Errorf("%s: %w", f.Name(), err)
		}
		for _, stmt := range stmts {
			if _, err := db.ExecContext(ctx, stmt); err != nil {
				db.Close()
				return nil, nil, fmt.Errorf("%s: %w", f.Name(), err)
			}
		}
	}
	drv, err := sqlite.Open(db)
	if err != nil {
		db.Close()
		return nil, nil, err
	}
	return db, drv, nil
}
